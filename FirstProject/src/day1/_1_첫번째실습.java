package day1;

public class _1_첫번째실습 {
	public static void main(String[] args) {
//		프린트문 자동 완성은 syso(텍스트) + ctrl + space
		 
		System.out.println("Hello Java");
		System.out.println(100); // 숫자
		System.out.println("100"); // 문자
		
		System.out.println(100 + 5); // 숫자 + 숫자 => 숫자
		System.out.println("100" + 5); // 문자에 덧셈을 하면 이어붙이기가 됨
//		System.out.println("100" * 5); 문자열에 곱셈은 불가
		
	}
}
