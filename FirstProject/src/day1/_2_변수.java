package day1;

public class _2_변수 {

	public static void main(String[] args) {
		// 변수
		// 변수는 값을 저장하는 공간
		String 이름 = "홍길동";
		System.out.println(이름); // '홍길동' 출력
		System.out.println("이름"); // '이름' 출력
		
		// 다만, 변수는 기본적으로 영어 사용을 권장
		int age = 30;
		double height = 170.5;
		
		// boolean(참 or 거짓)
		// true or false
		boolean isMarried = false;
		
		
		// 변수를 선언할 때 카멜(camel)표기법을 사용
		// 변수는 소문자로 시작
		// 두개 이상의 단어를 조합해서 변수를 만들 때
		// 첫 단어를 제외한 단어 시작 시 대문자로 시작
		
		// 학번 => studentnumber
		// studentNumber => stuNum(줄임말은 상황에 맞게)
		
		// 변수는 의미있는 값을 사용
		
		int a = 50; // x
		int weight = 50; // o
		
		// 변수는 카멜표기법 지킬 것
		// 소문자로 시작할 것
		// 의미있는 단어를 사용할 것
		// String(문자), int(정수), double(실수), boolean(참거짓)
		
		
	}
}
